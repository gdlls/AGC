package agc.bench;

import java.util.Locale;
import java.util.concurrent.ThreadLocalRandom;

/**
 * The five canonical AGC benchmark scenarios (roadmap Phase 1-2).
 *
 * <ul>
 *   <li>{@code dense-combat} — hundreds of players packed into a small radius with constant swings.</li>
 *   <li>{@code redstone-storm} — bots observe an operator-provided active circuit area (server load
 *       comes from the circuit itself; supply a prepared world).</li>
 *   <li>{@code teleport-storm} — continuous /tp churn to random coordinates.</li>
 *   <li>{@code chunk-gen-storm} — spectators flying into ungenerated terrain.</li>
 *   <li>{@code login-storm} — join/leave churn at a target rate (default target: 100/s).</li>
 * </ul>
 */
public final class Scenarios {

    private Scenarios() {}

    public static Scenario byName(final String name) {
        return byName(name, 100, 25.0);
    }

    public static Scenario byName(final String name, final int targetBots, final double joinRate) {
        return switch (name.toLowerCase(Locale.ROOT)) {
            case "dense-combat" -> denseCombat();
            case "redstone-storm" -> redstoneStorm();
            case "teleport-storm" -> teleportStorm();
            case "chunk-gen-storm" -> chunkGenStorm();
            case "login-storm" -> loginStorm(targetBots, joinRate);
            default -> throw new IllegalArgumentException(
                "unknown scenario: " + name + " (expected dense-combat|redstone-storm|teleport-storm|chunk-gen-storm|login-storm)");
        };
    }

    public static Scenario denseCombat() {
        return new Scenario() {
            @Override public String name() { return "dense-combat"; }
            @Override public int durationTicks() { return 20 * 300; } // 5 minutes

            @Override public void onBotTick(final BotHandle bot, final int tick) {
                // Tight random walk inside ~8 block radius around spawn point.
                if (tick % 4 == 0) {
                    final double angle = ThreadLocalRandom.current().nextDouble(Math.PI * 2);
                    bot.moveToward(64 + Math.cos(angle) * 8, 64 + Math.sin(angle) * 8);
                }
                if (tick % 10 == 0) {
                    bot.swingArm();
                }
            }
        };
    }

    public static Scenario redstoneStorm() {
        return new Scenario() {
            @Override public String name() { return "redstone-storm"; }
            @Override public int durationTicks() { return 20 * 300; }

            // Operator must prepare a world containing active circuits and point bots at it
            // (e.g. via --spawn-x/--spawn-z options). Server load is generated by the circuit,
            // not the bots; this scenario validates tracker/broadcast cost under that load.
            @Override public String[] serverSetupCommands() {
                return new String[] { "gamerule randomTickSpeed 1" };
            }

            @Override public void onBotTick(final BotHandle bot, final int tick) {
                if (tick % 40 == 0) {
                    final double angle = ThreadLocalRandom.current().nextDouble(Math.PI * 2);
                    bot.moveToward(64 + Math.cos(angle) * 16, 64 + Math.sin(angle) * 16);
                }
            }
        };
    }

    public static Scenario teleportStorm() {
        return new Scenario() {
            private static final double RADIUS = 512.0;

            @Override public String name() { return "teleport-storm"; }
            @Override public int durationTicks() { return 20 * 180; } // 3 minutes

            @Override public String[] serverSetupCommands() {
                return new String[] { "gamerule sendCommandFeedback false" };
            }

            @Override public void onBotTick(final BotHandle bot, final int tick) {
                // Stagger bots across ticks so the storm spreads over the tick window.
                if ((tick + System.identityHashCode(bot)) % 20 == 0) {
                    final double x = ThreadLocalRandom.current().nextDouble(-RADIUS, RADIUS);
                    final double z = ThreadLocalRandom.current().nextDouble(-RADIUS, RADIUS);
                    bot.runCommand("tp " + String.format(Locale.ROOT, "%.1f", x) + " 128 "
                        + String.format(Locale.ROOT, "%.1f", z));
                }
            }
        };
    }

    public static Scenario chunkGenStorm() {
        return new Scenario() {
            @Override public String name() { return "chunk-gen-storm"; }
            @Override public int durationTicks() { return 20 * 240; } // 4 minutes

            @Override public String[] serverSetupCommands() {
                return new String[] { "defaultgamemode spectator", "gamemode spectator @a" };
            }

            @Override public void onBotTick(final BotHandle bot, final int tick) {
                // Continuous forward flight into ungenerated terrain.
                bot.moveToward(1_000_000 + tick * 8, ThreadLocalRandom.current().nextDouble(-256, 256));
            }
        };
    }

    public static Scenario loginStorm(final double churnPerSecond) {
        return loginStorm(100, churnPerSecond);
    }

    public static Scenario loginStorm(final int targetBots, final double churnPerSecond) {
        final double rate = Math.max(1.0, churnPerSecond);
        final int lifetimeTicks = Math.max(20, (int) Math.round((targetBots / rate) * 20.0));
        return new Scenario() {
            @Override public String name() { return "login-storm"; }
            @Override public int durationTicks() { return 20 * 120; } // 2 minutes
            @Override public boolean isLoginChurn() { return true; }
            @Override public double churnPerSecond() { return rate; }
            @Override public void onBotTick(final BotHandle bot, final int tick) {
                // Churning sessions only need to survive the join sequence briefly.
                // Apply deterministic per-bot jitter (+/- 10 ticks) so sessions desynchronize smoothly.
                final int jitter = Math.abs(System.identityHashCode(bot)) % 21 - 10;
                if (tick >= Math.max(20, lifetimeTicks + jitter)) {
                    bot.disconnect();
                }
            }
        };
    }
}
