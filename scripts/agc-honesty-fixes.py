"""AGC honesty fixes — scripted, exact-string edits to the generated NMS tree.

Why this script exists
----------------------
`paper-server/src/minecraft/**` is git-ignored (Paper convention: it is regenerated by
`paperweight`'s `applyPatches`). The file-editing tools in this workspace respect ignore rules, so
the AGC NMS-tree fixes below cannot be applied with them. They are applied with this script instead,
and every edit is verified afterwards by diffing against the pre-edit tree backup:

    diff -ru paper-server/src/minecraft/java build/verify/minecraft-tree-backup/java

The script is intentionally strict: if an anchor string is missing or ambiguous it fails loudly
instead of writing a partial edit. It preserves CRLF line endings.

What it changes (all of it restores Paper behaviour that AGC had changed without a config gate)
-----------------------------------------------------------------------------------------------
1. Mob.java            - removes the per-tick `(tickCount + id) % 2` AI gate plus the DAP distance
                         throttle and the AI batch split (mobs re-evaluate goals every tick again).
2. Brain.java          - removes the sensor/behaviour throttle (brains sense every tick again).
3. Villager.java       - removes the 1-in-20 brain tick for stationary villagers.
4. ItemEntity.java     - restores vanilla's `(tickCount + id) % 4` condition (drops AGC's 10-tick
                         extension).
5. AbstractArrow.java  - removes the grounded-arrow early return (arrow support-state checks run
                         every tick again).
6. ObserverBlock.java  - removes the depth-64 observer-chain limiter (silently dropped neighbour
                         updates for deeper chains, breaking legitimate redstone machines).
7. ExperienceOrb.java  - gates the orb sleep behind the new `entitySleepOptimizer` flag (default
                         off).
8. PathNavigation.java - gates the async pathfinding pipeline behind the new `asyncPathfinding`
                         flag (default off; off-thread pathfinding also needs a thread-safety proof).
"""

