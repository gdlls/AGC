def main() -> int:
    failures: list[str] = []
    applied = 0
    for rel_path, old_lf, new_lf in EDITS:
        path = NMS_ROOT / rel_path
        if not path.is_file():
            failures.append(f"missing file: {rel_path}")
            continue
        text = path.read_text(encoding="utf-8", newline="")
        crlf = "\r\n" in text
        old = old_lf.replace("\n", "\r\n") if crlf else old_lf
        new = new_lf.replace("\n", "\r\n") if crlf else new_lf
        count = text.count(old)
        if count == 0:
            failures.append(f"anchor not found in {rel_path}")
            continue
        if count > 1:
            failures.append(f"anchor ambiguous ({count}x) in {rel_path}")
            continue
        path.write_text(text.replace(old, new), encoding="utf-8", newline="")
        applied += 1
        print(f"  patched {rel_path}")

    print(f"\n{applied}/{len(EDITS)} edits applied")
    if failures:
        print("FAILURES:")
        for f in failures:
            print(f"  - {f}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
